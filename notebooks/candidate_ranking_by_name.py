"""## Step 5: Calculate Match Scores

We use **cosine similarity** to measure how similar each resume is to the job description.

**How it works:**
- Converts text to numbers using TF-IDF
- Compares the job description with each resume
- Gives a score from 0 to 100 (100 = perfect match)
"""

# Combine job description with all resumes for TF-IDF
all_documents = [cleaned_job_description] + candidates_df['cleaned_resume'].tolist()

# Create TF-IDF vectors
# ngram_range=(1,2) means we look at single words AND word pairs
# This helps catch phrases like "machine learning" or "data science"
tfidf_vectorizer = TfidfVectorizer(
    stop_words='english',
    max_features=1500,
    ngram_range=(1, 2)
)

tfidf_matrix = tfidf_vectorizer.fit_transform(all_documents)

# Calculate similarity between job description (first document) and all resumes
job_vector = tfidf_matrix[0:1]  # Job description vector
resume_vectors = tfidf_matrix[1:]  # All resume vectors

# Calculate cosine similarity
similarity_scores = cosine_similarity(job_vector, resume_vectors)[0]

# Convert to percentage (0-100)
similarity_scores_percent = similarity_scores * 100

# Add scores to dataframe
candidates_df['match_score'] = similarity_scores_percent

print("✓ Match scores calculated!")
print(f"\nHighest score: {similarity_scores_percent.max():.2f}%")
print(f"Lowest score: {similarity_scores_percent.min():.2f}%")
print(f"Average score: {similarity_scores_percent.mean():.2f}%")

