"""## Step 10: Score Categories

Let's categorize candidates by their match score:
"""

def categorize_match(score):
    """Categorize candidates based on match score"""
    if score >= 70:
        return 'Excellent Match'
    elif score >= 50:
        return 'Good Match'
    elif score >= 30:
        return 'Fair Match'
    else:
        return 'Poor Match'

