"""## Step 3: Text Cleaning Function

This removes unnecessary characters and formats the text:
"""

def cleanResume(resumeText):
    """
    Clean resume text by removing:
    - URLs
    - Special characters
    - Extra spaces
    - Non-ASCII characters
    """
    # Convert to string if not already
    resumeText = str(resumeText)

    resumeText = re.sub('http\S+\s*', ' ', resumeText)  # remove URLs
    resumeText = re.sub('RT|cc', ' ', resumeText)  # remove RT and cc
    resumeText = re.sub('#\S+', '', resumeText)  # remove hashtags
    resumeText = re.sub('@\S+', '  ', resumeText)  # remove mentions
    resumeText = re.sub('[%s]' % re.escape("""!"#$%&'()*+,-./:;<=>?@[\]^_`{|}~"""), ' ', resumeText)  # remove punctuations
    resumeText = re.sub(r'[^\x00-\x7f]',r' ', resumeText)  # remove non-ASCII
    resumeText = re.sub('\s+', ' ', resumeText)  # remove extra whitespace
    return resumeText.strip()

# Apply cleaning to all resumes
candidates_df['cleaned_resume'] = candidates_df['resume_text'].apply(lambda x: cleanResume(x))
print("✓ All resumes cleaned successfully!")

