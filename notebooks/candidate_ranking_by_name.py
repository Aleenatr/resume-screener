"""## Step 8: Extract Key Skills from Top Candidates

This function finds important keywords in each candidate's resume:
"""

def extract_key_skills(resume_text, job_desc_text, top_n=10):
    """
    Extract key skills/keywords that appear in the resume
    """
    # Get TF-IDF features for this resume
    vectorizer = TfidfVectorizer(stop_words='english', max_features=100, ngram_range=(1,2))

    # Fit on both job description and resume
    vectorizer.fit([job_desc_text, resume_text])

    # Get feature names (words)
    feature_names = vectorizer.get_feature_names_out()

    # Transform resume
    resume_vector = vectorizer.transform([resume_text])

    # Get scores for each word
    scores = resume_vector.toarray()[0]

    # Get top words
    top_indices = scores.argsort()[-top_n:][::-1]
    top_skills = [feature_names[i] for i in top_indices if scores[i] > 0]

    return top_skills

